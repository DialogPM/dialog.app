#!/usr/bin/env python3
"""Generates lib/l10n/strings.g.dart from the desktop translations (app/src/locales/*.json)
plus the mobile-only strings in tool/mobile_strings.json. Run from the mobile/ directory:

    python3 tool/gen_strings.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LOCALES = os.path.join(ROOT, "..", "app", "src", "locales")
LANGS = ["en", "ro", "it"]


def flatten(d, prefix=""):
    out = {}
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(flatten(v, key + "."))
        else:
            out[key] = str(v)
    return out


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


extra = json.load(open(os.path.join(HERE, "mobile_strings.json"), encoding="utf-8"))
lines = [
    "// GENERATED by tool/gen_strings.py from app/src/locales/*.json and tool/mobile_strings.json.",
    "// Do not edit by hand.",
    "",
    "const Map<String, Map<String, String>> kStrings = {",
]
for lang in LANGS:
    data = flatten(json.load(open(os.path.join(LOCALES, f"{lang}.json"), encoding="utf-8")))
    # Mobile-only strings never override the shared desktop ones.
    for k, v in flatten(extra[lang]).items():
        data.setdefault(k, v)
    lines.append(f"  '{lang}': {{")
    for k in sorted(data):
        lines.append(f"    {dart_str(k)}: {dart_str(data[k])},")
    lines.append("  },")
lines.append("};")
lines.append("")
open(os.path.join(ROOT, "lib", "l10n", "strings.g.dart"), "w", encoding="utf-8").write("\n".join(lines))
print("ok")
